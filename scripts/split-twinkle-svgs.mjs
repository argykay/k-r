import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { parse } from 'node-html-parser';
import { svgPathBbox } from 'svg-path-bbox';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'src/assets/svgs/twinkles');

const SOURCES = [
  { name: 'twinkle-1', file: path.join(root, 'src/assets/svgs/twinkle_1.svg') },
  { name: 'twinkle-2', file: path.join(root, 'src/assets/svgs/twinkle_2.svg') },
];

const PADDING = 4;

function cropPath(pathD) {
  const [minX, minY, maxX, maxY] = svgPathBbox(pathD);
  const x = minX - PADDING;
  const y = minY - PADDING;
  const width = maxX - minX + PADDING * 2;
  const height = maxY - minY + PADDING * 2;

  return {
    viewBox: `${x} ${y} ${width} ${height}`,
    width,
    height,
    centerX: (minX + maxX) / 2,
    centerY: (minY + maxY) / 2,
  };
}

function toSvg(pathD, viewBox) {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="100%" height="100%">`,
    `  <path fill="currentColor" d="${pathD}"/>`,
    '</svg>',
  ].join('\n');
}

fs.mkdirSync(outDir, { recursive: true });

const manifest = [];

for (const source of SOURCES) {
  const xml = fs.readFileSync(source.file, 'utf8');
  const doc = parse(xml, { lowerCaseTagName: false });
  const svg = doc.querySelector('svg');
  const viewBoxParts = (svg.getAttribute('viewBox') || '0 0 1 1').split(/\s+/).map(Number);
  const parentWidth = viewBoxParts[2] ?? 1;
  const parentHeight = viewBoxParts[3] ?? 1;
  const paths = svg.querySelectorAll('path');

  paths.forEach((node, index) => {
    const pathD = node.getAttribute('d');
    if (!pathD) return;

    const id = `${source.name}-${String(index + 1).padStart(2, '0')}`;
    const crop = cropPath(pathD);
    const filename = `${id}.svg`;
    fs.writeFileSync(path.join(outDir, filename), toSvg(pathD, crop.viewBox));

    manifest.push({
      id,
      file: filename,
      source: source.name,
      width: Math.round(crop.width * 10) / 10,
      height: Math.round(crop.height * 10) / 10,
      normX: Math.round((crop.centerX / parentWidth) * 1000) / 1000,
      normY: Math.round((crop.centerY / parentHeight) * 1000) / 1000,
    });
  });
}

fs.writeFileSync(
  path.join(outDir, 'manifest.json'),
  JSON.stringify(manifest, null, 2)
);

const importLines = manifest.map((entry) => {
  const symbol = entry.id.replace(/-/g, '_');
  return `import { ReactComponent as ${symbol}Svg } from './${entry.file}';`;
});

const assetLines = manifest.map((entry) => {
  const symbol = entry.id.replace(/-/g, '_');
  return `  {
    id: '${entry.id}',
    Svg: ${symbol}Svg,
    width: ${entry.width},
    height: ${entry.height},
    normX: ${entry.normX},
    normY: ${entry.normY},
  },`;
});

const indexTs = `/* Auto-generated by scripts/split-twinkle-svgs.mjs — do not edit manually */
import type { FC, SVGProps } from 'react';
${importLines.join('\n')}

export type TwinkleAsset = {
  id: string;
  Svg: FC<SVGProps<SVGSVGElement>>;
  width: number;
  height: number;
  normX: number;
  normY: number;
};

export const TWINKLE_ASSETS: TwinkleAsset[] = [
${assetLines.join('\n')}
];
`;

fs.writeFileSync(path.join(outDir, 'index.ts'), indexTs);

console.log(`Wrote ${manifest.length} twinkle SVGs to ${outDir}`);
